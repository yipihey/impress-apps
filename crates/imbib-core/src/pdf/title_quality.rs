/// Foundation `CharacterSet.newlines`: U+000A–U+000D, U+0085, U+2028, U+2029.
///
/// `str::lines()` is not a substitute — it treats `\r\n` as one break, ignores a
/// lone `\r`, and ignores U+2028/U+2029 entirely. PDF text extraction emits all
/// of these.
fn is_newline(c: char) -> bool {
    matches!(
        c,
        '\n' | '\u{000B}' | '\u{000C}' | '\r' | '\u{0085}' | '\u{2028}' | '\u{2029}'
    )
}

/// **Retired.** Swift-parity reference port of
/// `PDFMetadataExtractor.extractTitleFromFirstPage`.
///
/// This is the drifted duplicate of
/// [`crate::pdf::metadata_heuristics`]'s `extract_title`, and it is strictly
/// worse than it in five ways: it scans 20 lines instead of 25, keeps 2
/// candidates instead of 3, has a shorter skip-pattern list (no `received`,
/// `vol.`, `no.`, `©`, `introduction`, `keywords:`, `pacs:`, `msc:`), never
/// checks for `department`/`laboratory` affiliations, does not stop once it has
/// passed an author line, and does not run `clean_title`. The visible
/// consequence, pinned in `stage7_pdf_parity.rs`, is that on a normal paper it
/// glues the author line onto the end of the title.
///
/// It exists ONLY so the parity suite can prove the port reproduces the Swift
/// behaviour and then demonstrate, on the same eight inputs, what the surviving
/// implementation does instead. Production code must call
/// `extract_metadata_heuristics_internal` — do not wire this up.
pub fn swift_first_page_title(text: &str) -> Option<String> {
    let lines: Vec<&str> = text
        .split(is_newline)
        .map(trim_ws)
        .filter(|l| !l.is_empty())
        .collect();

    let mut candidate_lines: Vec<&str> = Vec::new();

    for line in lines.iter().take(20) {
        let lowercased = line.to_lowercase();

        if SWIFT_FIRST_PAGE_SKIP_PATTERNS
            .iter()
            .any(|p| lowercased.contains(p))
        {
            continue;
        }

        if swift_count(line) < 10 {
            continue;
        }

        // Swift: `lowercased.contains(" and ") && line.filter { $0.isUppercase }.count > 3`.
        // Counted over scalars rather than grapheme clusters; the two differ
        // only for a decomposed uppercase letter, which cannot change a `> 3`
        // verdict without also changing it in Swift.
        if lowercased.contains(" and ") && line.chars().filter(|c| c.is_uppercase()).count() > 3 {
            continue;
        }

        if lowercased.contains('@')
            || lowercased.contains("university")
            || lowercased.contains("institute")
        {
            continue;
        }

        candidate_lines.push(line);

        if candidate_lines.len() >= 2 {
            break;
        }
    }

    if candidate_lines.len() >= 2 {
        let combined = candidate_lines.join(" ");
        if swift_count(&combined) <= 300 {
            return Some(combined);
        }
    }

    candidate_lines.first().map(|l| (*l).to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn six_visible_character_floor_ignores_surrounding_whitespace() {
        assert!(!is_plausible_title("  ab  "));
        assert!(is_plausible_title("  abcdef  "));
    }

    #[test]
    fn zero_width_space_is_trimmed_like_foundation_does() {
        // Rust's `str::trim()` leaves U+200B in place, so a naive port would
        // measure 6 clusters here and disagree with Swift on the floor.
        assert_eq!(trim_ws_nl("\u{200B}abcde\u{200B}"), "abcde");
        assert!(!is_plausible_title("\u{200B}abcde\u{200B}"));
    }

    #[test]
    fn anchored_patterns_do_not_fire_mid_string() {
        assert!(is_plausible_title("Erratum 1234-5678(96)00123-4"));
        assert!(is_plausible_title("A title with 10.1038/x inside it"));
    }

    #[test]
    fn has_identifier_is_an_or_over_all_three() {
        let mut fields = PdfExtractedFields::default();
        assert!(!fields.has_identifier());
        fields.extracted_bibcode = Some("2023ApJ...123..456A".into());
        assert!(fields.has_identifier());
    }
}

//! Generates `docs/verbs/<service>.md` — one reference page per service,
//! built straight from the linked `VerbDescriptor` inventory (plan
//! auto-gui-and-self-docs.md, work package G3; findings D-1, D-2).
//!
//! Every verb's page section holds: its description (the trait method's
//! doc), its arguments (from the input schema, with each property's
//! `description` — G-4's fix), its safety class and effects, and its
//! examples (G3's `#[impress_example]`s, printed as the same JSON a form
//! would prefill and Tier A runs). `guide.md` links here instead of
//! hand-naming verbs (D-2); `docs/verbs/*.md` is generated output, never
//! hand-edited — `scripts/check-verb-docs.sh` regenerates it and fails the
//! build on a diff, the same shape as `check-verb-coverage.sh`.
//!
//! `impress-capabilities` links every service by default (`full`), so this
//! binary sees the whole inventory with no extra wiring:
//! `cargo run -p impress-capabilities --bin gen-verb-docs`.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use impress_service_core::VerbDescriptor;
use serde_json::Value;

fn repo_root() -> PathBuf {
    // This binary's crate is two levels under the repo root
    // (crates/impress-capabilities), same convention as the test helpers in
    // this crate's `tests/*.rs`.
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("crates/impress-capabilities has two parents")
        .to_path_buf()
}

/// Markdown-escape a string for use inside a table cell (pipes and
/// newlines, the two things that break a Markdown table row).
fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

fn render_service(service: &str, verbs: &[&'static VerbDescriptor]) -> String {
    let mut out = String::new();
    out.push_str(&format!("# {service}\n\n"));
    out.push_str(
        "Generated by `cargo run -p impress-capabilities --bin gen-verb-docs`. \
         Do not hand-edit — `scripts/check-verb-docs.sh` regenerates this file \
         and fails CI on a diff.\n\n",
    );
    for v in verbs {
        out.push_str(&format!("## `{}`\n\n", v.name));
        out.push_str(v.description.trim());
        out.push_str("\n\n");
        out.push_str(&format!(
            "- **safety**: `{}`{}\n",
            v.safety.class.as_str(),
            if v.safety.idempotent {
                ", idempotent"
            } else {
                ""
            }
        ));
        if let Some(dep) = v.deprecated {
            if v.aliases.is_empty() {
                out.push_str(&format!(
                    "- **deprecated** since `{}`: {}\n",
                    dep.since, dep.note
                ));
            }
        }
        if !v.aliases.is_empty() {
            let names: Vec<String> = v.aliases.iter().map(|a| format!("`{a}`")).collect();
            out.push_str(&format!(
                "- **aliases** (deprecated since `{}`; still callable, never listed): {}\n",
                v.deprecated.map(|d| d.since).unwrap_or("—"),
                names.join(", ")
            ));
        }
        out.push_str(&format!(
            "- **reads**: {}\n",
            if v.effects.reads.is_empty() {
                "—".to_string()
            } else {
                v.effects
                    .reads
                    .iter()
                    .map(|k| k.describe())
                    .collect::<Vec<_>>()
                    .join(", ")
            }
        ));
        out.push_str(&format!(
            "- **writes**: {}\n",
            if v.effects.writes.is_empty() {
                "—".to_string()
            } else {
                v.effects
                    .writes
                    .iter()
                    .map(|k| k.describe())
                    .collect::<Vec<_>>()
                    .join(", ")
            }
        ));
        out.push_str(&format!(
            "- **reach**: {}\n",
            if v.effects.reach.is_empty() {
                "—".to_string()
            } else {
                v.effects
                    .reach
                    .iter()
                    .map(|r| r.describe())
                    .collect::<Vec<_>>()
                    .join(", ")
            }
        ));
        out.push('\n');

        let schema = (v.input_schema)();
        let props = schema
            .get("properties")
            .and_then(Value::as_object)
            .cloned()
            .unwrap_or_default();
        if props.is_empty() {
            out.push_str("Takes no arguments.\n\n");
        } else {
            let required: Vec<String> = schema
                .get("required")
                .and_then(Value::as_array)
                .map(|a| {
                    a.iter()
                        .filter_map(|v| v.as_str().map(str::to_string))
                        .collect()
                })
                .unwrap_or_default();
            out.push_str("| Argument | Type | Required | Description |\n");
            out.push_str("|---|---|---|---|\n");
            for (name, prop) in &props {
                let ty = prop
                    .get("type")
                    .and_then(Value::as_str)
                    .unwrap_or("—")
                    .to_string();
                let req = if required.contains(name) { "yes" } else { "no" };
                let desc = prop
                    .get("description")
                    .and_then(Value::as_str)
                    .unwrap_or("*(undocumented)*");
                out.push_str(&format!(
                    "| `{}` | {} | {} | {} |\n",
                    cell(name),
                    cell(&ty),
                    req,
                    cell(desc)
                ));
            }
            out.push('\n');
        }

        if v.examples.is_empty() {
            out.push_str("_No examples yet._\n\n");
        } else {
            out.push_str("**Examples**\n\n");
            for ex in v.examples {
                out.push_str(&format!("- `{}`:\n\n", ex.name));
                out.push_str("  ```json\n");
                out.push_str(&format!("  {}\n", ex.args));
                out.push_str("  ```\n");
                if let Some(expect) = ex.expect {
                    out.push_str("  expects:\n\n  ```json\n");
                    out.push_str(&format!("  {expect}\n"));
                    out.push_str("  ```\n");
                }
                out.push('\n');
            }
        }
    }
    out
}

fn main() {
    // Without this call the linker is free to strip every service crate's
    // object code — nothing else in this binary references a symbol from
    // them, only their `inventory::submit!` side effects (see this crate's
    // module docs, "Why a linker workaround at all").
    impress_capabilities::force_link();

    let mut by_service: BTreeMap<&'static str, Vec<&'static VerbDescriptor>> = BTreeMap::new();
    for v in VerbDescriptor::iter() {
        by_service.entry(v.service).or_default().push(v);
    }
    for verbs in by_service.values_mut() {
        verbs.sort_by_key(|v| v.name);
    }

    let out_dir = repo_root().join("docs/verbs");
    fs::create_dir_all(&out_dir).expect("create docs/verbs");

    // Remove pages for services no longer linked, so a retired service's
    // page does not linger and pass the diff check by accident.
    let wanted: std::collections::BTreeSet<String> =
        by_service.keys().map(|s| format!("{s}.md")).collect();
    if let Ok(entries) = fs::read_dir(&out_dir) {
        for entry in entries.flatten() {
            let name = entry.file_name().to_string_lossy().to_string();
            if name.ends_with(".md") && name != "README.md" && !wanted.contains(&name) {
                let _ = fs::remove_file(entry.path());
            }
        }
    }

    let mut index = String::new();
    index.push_str("# Verb reference\n\n");
    index.push_str(
        "One page per service, generated from the linked `VerbDescriptor` \
         inventory. Regenerate with `cargo run -p impress-capabilities \
         --bin gen-verb-docs`; `scripts/check-verb-docs.sh` fails CI on a \
         diff.\n\n",
    );
    for (service, verbs) in &by_service {
        let page = render_service(service, verbs);
        fs::write(out_dir.join(format!("{service}.md")), page).expect("write page");
        index.push_str(&format!(
            "- [{service}]({service}.md) ({} verbs)\n",
            verbs.len()
        ));
    }
    fs::write(out_dir.join("README.md"), index).expect("write index");

    eprintln!(
        "wrote {} service pages to {}",
        by_service.len(),
        out_dir.display()
    );
}
